auto printer::print_call(call const& exp) -> void
{
    switch (exp.kind())
    {
        case node::expr_function:
            print_expr_function(exp.as<expr_function>());
            break;
        case node::expr_pointer:
            print_expr_pointer(exp.as<expr_pointer>());
            break;
        default:
            break;
    }
}

auto printer::print_expr_function(expr_function const& exp) -> void
{
    if (exp.mode == call::mode::thread)
        std::format_to(std::back_inserter(buf_), "thread ");
    else if (exp.mode == call::mode::childthread)
        std::format_to(std::back_inserter(buf_), "childthread ");

    if (exp.path->value != "")
    {
        print_expr_path(*exp.path);
        std::format_to(std::back_inserter(buf_), "::");
    }

    print_expr_identifier(*exp.name);
    std::format_to(std::back_inserter(buf_), "(");
    print_expr_arguments(*exp.args);
    std::format_to(std::back_inserter(buf_), ")");
}

auto printer::print_expr_pointer(expr_pointer const& exp) -> void
{
    if (exp.mode == call::mode::builtin)
        std::format_to(std::back_inserter(buf_), "call ");
    else if (exp.mode == call::mode::thread)
        std::format_to(std::back_inserter(buf_), "thread ");
    else if (exp.mode == call::mode::childthread)
        std::format_to(std::back_inserter(buf_), "childthread ");

    std::format_to(std::back_inserter(buf_), "[[ ");
    print_expr(*exp.func);
    std::format_to(std::back_inserter(buf_), " ]](");
    print_expr_arguments(*exp.args);
    std::format_to(std::back_inserter(buf_), ")");
}

