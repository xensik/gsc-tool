auto printer::print_stmt_empty(stmt_empty const&) -> void
{
    std::format_to(std::back_inserter(buf_), ";");
}

auto printer::print_stmt_list(stmt_list const& stm) -> void
{
    auto last_special = false;
    indent_ += 4;

    for (auto const& entry : stm.list)
    {
        if ((&entry != &stm.list.front() && entry->is_special_stmt()) || last_special)
            std::format_to(std::back_inserter(buf_), "\n");

        if (entry->is<stmt_dev>())
        {
            print_stmt(*entry);
        }
        else
        {
            std::format_to(std::back_inserter(buf_), "{: >{}}", "", indent_);
            print_stmt(*entry);
        }

        if (&entry != &stm.list.back())
            std::format_to(std::back_inserter(buf_), "\n");

        if (entry->is_special_stmt())
            last_special = true;
        else
            last_special = false;
    }

    indent_ -= 4;
}

auto printer::print_stmt_comp(stmt_comp const& stm) -> void
{
    std::format_to(std::back_inserter(buf_), "{: >{}}\n", "{", indent_ + 1);
    print_stmt_list(*stm.block);
    std::format_to(std::back_inserter(buf_), "\n{: >{}}", "}", indent_ + 1);
}

auto printer::print_stmt_dev(stmt_dev const& stm) -> void
{
    std::format_to(std::back_inserter(buf_), "/#\n");
    print_stmt_list(*stm.block);
    std::format_to(std::back_inserter(buf_), "\n#/");
}

auto printer::print_stmt_expr(stmt_expr const& stm) -> void
{
    switch (stm.value->kind())
    {
        case node::expr_increment:
            print_expr_increment(stm.value->as<expr_increment>());
            break;
        case node::expr_decrement:
            print_expr_decrement(stm.value->as<expr_decrement>());
            break;
        case node::expr_assign:
            print_expr_assign(stm.value->as<expr_assign>());
            break;
        case node::expr_call:
            print_expr_call(stm.value->as<expr_call>());
            break;
        case node::expr_method:
            print_expr_method(stm.value->as<expr_method>());
            break;
        case node::expr_empty:
            break;
        default:
            break; // throw error
    }

    std::format_to(std::back_inserter(buf_), ";");
}

