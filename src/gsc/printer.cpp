printer::printer(context* ctx) : ctx_{ ctx }
{
}

auto printer::print(assembly const& data) -> std::vector<u8>
{
    buf_ = std::vector<u8>{};
    buf_.reserve(0x10000);

    std::format_to(std::back_inserter(buf_), "// {} GSC ASSEMBLY\n", ctx_->engine_name());
    std::format_to(std::back_inserter(buf_), "// Generated by https://github.com/xensik/gsc-tool\n");

    print_assembly(data);

    return std::move(buf_);
}

auto printer::print(program const& data) -> std::vector<u8>
{
    buf_ = std::vector<u8>{};
    buf_.reserve(0x10000);

    std::format_to(std::back_inserter(buf_), "// {} GSC SOURCE\n", ctx_->engine_name());
    std::format_to(std::back_inserter(buf_), "// Generated by https://github.com/xensik/gsc-tool\n");

    print_program(data);

    return std::move(buf_);
}

auto printer::print_assembly(assembly const& data) -> void
{
    for (auto const& func : data.functions)
    {
        print_function(*func);
    }
}

auto printer::print_function(function const& func) -> void
{
    std::format_to(std::back_inserter(buf_), "\nsub:{}\n", func.name);

    for (auto const& inst : func.instructions)
    {
        if (auto const itr = func.labels.find(inst->index); itr != func.labels.end())
        {
            std::format_to(std::back_inserter(buf_), "\t{}\n", itr->second);
        }

        print_instruction(*inst);
    }

    std::format_to(std::back_inserter(buf_), "end:{}\n", func.name);
}

auto printer::print_instruction(instruction const& inst) -> void
{
    std::format_to(std::back_inserter(buf_), "\t\t{}", ctx_->opcode_name(inst.opcode));

    switch (inst.opcode)
    {
        case opcode::OP_GetString:
        case opcode::OP_GetIString:
        case opcode::OP_GetAnimTree:
            std::format_to(std::back_inserter(buf_), " {}", utils::string::to_literal(inst.data[0]));
            break;
        case opcode::OP_GetAnimation:
            std::format_to(std::back_inserter(buf_), " {}", utils::string::to_literal(inst.data[0]));
            std::format_to(std::back_inserter(buf_), " {}", utils::string::to_literal(inst.data[1]));
            break;
        case opcode::OP_endswitch:
        {
            auto count = static_cast<u32>(std::stoul(inst.data[0]));
            auto index = 1;

            std::format_to(std::back_inserter(buf_), " {}\n", count);

            for (auto i = 0u; i < count; i++)
            {
                if (inst.data[index] == "case")
                {
                    auto type = static_cast<switch_type>(std::stoul(inst.data[index + 1]));
                    auto data = (type == switch_type::integer) ? std::format("{}", inst.data[index + 2]) : utils::string::to_literal(inst.data[index + 2]);
                    std::format_to(std::back_inserter(buf_), "\t\t\t{} {} {}", inst.data[index], data, inst.data[index + 3]);
                    index += 4;
                }
                else if (inst.data[index] == "default")
                {
                    std::format_to(std::back_inserter(buf_), "\t\t\t{} {}", inst.data[index], inst.data[index + 1]);
                    index += 2;
                }

                if (i != count - 1)
                {
                    std::format_to(std::back_inserter(buf_), "\n");
                }
            }
            break;
        }
        default:
            for (auto const& entry : inst.data)
            {
                std::format_to(std::back_inserter(buf_), " {}", entry);
            }
            break;
    }

    std::format_to(std::back_inserter(buf_), "\n");
}

auto printer::print_program(program const& data) -> void
{
    for (auto const& inc : data.includes)
    {
        print_include(*inc);
    }

    for (auto const& dec : data.declarations)
    {
        std::format_to(std::back_inserter(buf_), "\n");
        print_decl(*dec);
    }
}

auto printer::print_include(include const& inc) -> void
{
    std::format_to(std::back_inserter(buf_), "#include ");
    print_expr_path(*inc.path);
    std::format_to(std::back_inserter(buf_), ";\n");
}

auto printer::print_decl(decl const& dec) -> void
{
    switch (dec.kind())
    {
        case node::decl_dev_begin:
            print_decl_dev_begin(dec.as<decl_dev_begin>());
            break;
        case node::decl_dev_end:
            print_decl_dev_end(dec.as<decl_dev_end>());
            break;
        case node::decl_usingtree:
            print_decl_usingtree(dec.as<decl_usingtree>());
            break;
        case node::decl_constant:
            print_decl_constant(dec.as<decl_constant>());
            break;
        case node::decl_function:
            print_decl_function(dec.as<decl_function>());
            break;
        case node::decl_empty:
            print_decl_empty(dec.as<decl_empty>());
            break;
        default:
            break;
    }
}

auto printer::print_decl_dev_begin(decl_dev_begin const&) -> void
{
    std::format_to(std::back_inserter(buf_), "/#");
}

auto printer::print_decl_dev_end(decl_dev_end const&) -> void
{
    std::format_to(std::back_inserter(buf_), "#/");
}

auto printer::print_decl_usingtree(decl_usingtree const& dec) -> void
{
    std::format_to(std::back_inserter(buf_), "#using_animtree(");
    print_expr_string(*dec.name);
    std::format_to(std::back_inserter(buf_), ");\n");
}

auto printer::print_decl_constant(decl_constant const& dec) -> void
{
    print_expr_identifier(*dec.name);
    std::format_to(std::back_inserter(buf_), " = ");
    print_expr(*dec.value);
    std::format_to(std::back_inserter(buf_), ";\n");
}

auto printer::print_decl_function(decl_function const& dec) -> void
{
    indent_ = 0;
    print_expr_identifier(*dec.name);
    std::format_to(std::back_inserter(buf_), "(");
    print_expr_parameters(*dec.params);
    std::format_to(std::back_inserter(buf_), ")\n");
    print_stmt_comp(*dec.body);
    std::format_to(std::back_inserter(buf_), "\n");
}

auto printer::print_decl_empty(decl_empty const&) -> void
{
    std::format_to(std::back_inserter(buf_), ";");
}

