auto printer::print_stmt_notify(stmt_notify const& stm) -> void
{
    print_expr(*stm.obj);
    std::format_to(std::back_inserter(buf_), " notify( ");
    print_expr(*stm.event);

    if (!stm.args->list.empty())
    {
        std::format_to(std::back_inserter(buf_), ",");
        print_expr_arguments(*stm.args);
    }
    else
    {
        std::format_to(std::back_inserter(buf_), " ");
    }

    std::format_to(std::back_inserter(buf_), ");");
}

auto printer::print_stmt_wait(stmt_wait const& stm) -> void
{
    if (stm.time->is<expr_float>() || stm.time->is<expr_integer>())
    {
        std::format_to(std::back_inserter(buf_), "wait ");
        print_expr(*stm.time);
        std::format_to(std::back_inserter(buf_), ";");
    }
    else if (stm.time->is<expr_paren>())
    {
        std::format_to(std::back_inserter(buf_), "wait");
        print_expr(*stm.time);
        std::format_to(std::back_inserter(buf_), ";");
    }
    else
    {
        std::format_to(std::back_inserter(buf_), "wait( ");
        print_expr(*stm.time);
        std::format_to(std::back_inserter(buf_), " );");
    }
}

